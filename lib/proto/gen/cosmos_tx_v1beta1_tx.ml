            serialize writer address sign_doc mode sig'

        let to_proto t =
          let writer = Runtime'.Writer.init () in
          to_proto' writer t;
          writer

        let from_proto_exn =
          let constructor address sign_doc mode sig' =
            { address; sign_doc; mode; sig' }
          in
          Runtime'.apply_lazy (fun () ->
              Runtime'.Deserialize.deserialize (spec ()) constructor)

        let from_proto writer =
          Runtime'.Result.catch (fun () -> from_proto_exn writer)

        let to_json options =
          let serialize =
            Runtime'.Serialize_json.serialize ~message_name:(name ()) (spec ())
              options
          in
          fun { address; sign_doc; mode; sig' } ->
            serialize address sign_doc mode sig'

        let from_json_exn =
          let constructor address sign_doc mode sig' =
            { address; sign_doc; mode; sig' }
          in
          Runtime'.apply_lazy (fun () ->
              Runtime'.Deserialize_json.deserialize ~message_name:(name ())
                (spec ()) constructor)

        let from_json json =
          Runtime'.Result.catch (fun () -> from_json_exn json)
      end
    end
  end
